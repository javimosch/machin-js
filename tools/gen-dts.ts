// Generate types/machin.d.ts (+ builtin name list) from `machin guide`, so builtins never drift.
//why: the guide is compiled into the machin binary — it is the one source of truth for what exists.
const guide = JSON.parse(new TextDecoder().decode(
  (await new Deno.Command("machin", { args: ["guide"] }).output()).stdout));

const MAP: Record<string, string> = { int: "number", float: "number", string: "string", bool: "boolean" };

/** `(string, int) -> string` -> TS params/return; anything fancier degrades to any. */
function sig(s: string): { params: string; ret: string } {
  const m = /^\((.*)\)\s*->\s*(.*)$/.exec(s);
  const simple = (t: string) => MAP[t.trim()] ?? "any";
  if (!m || /[\[|.]/.test(m[1])) return { params: "...args: any[]", ret: m ? simple(m[2]) : "any" };
  const ps = m[1].trim() === "" ? [] : m[1].split(",").map((t, i) => `a${i}: ${simple(t)}`);
  return { params: ps.join(", "), ret: simple(m[2]) };
}

let dts = `// GENERATED by tools/gen-dts.ts from \`machin guide\` (machin ${guide.version}). Do not edit.\n`;
const names: string[] = [];
for (const b of guide.builtins) {
  const { params, ret } = sig(b.sig);
  dts += `/** ${b.summary} */\nexport function ${b.name}(${params}): ${ret};\n`;
  names.push(b.name);
}
await Deno.writeTextFile("types/machin.d.ts", dts);
await Deno.writeTextFile("types/machin-builtins.json", JSON.stringify(names.sort()) + "\n");
console.log(`wrote ${names.length} builtins (machin ${guide.version})`);
