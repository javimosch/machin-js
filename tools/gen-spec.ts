// Generate docs/specification.md from the audited constructs and their pinned outcomes.
//why: a hand-written list of what works would drift; this one is the list the tests enforce.
import { SNIPPETS, type Snippet } from "../test/syntax_test.ts";
import EXPECTED from "../test/syntax_expected.json" with { type: "json" };

const spec: Record<string, string> = EXPECTED;

/** The snippet as one table cell: inline code, with pipes and backticks made safe. */
function cell([, body, after = "", before = ""]: Snippet): string {
  const extra = [before, after].join("").trim();
  const text = body.replace(/\s+/g, " ").trim() + (extra ? " …" : "");
  const short = text.length > 90 ? `${text.slice(0, 87)}…` : text;
  const safe = short.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\|/g, "&#124;").replace(/`/g, "&#96;");
  return `<code>${safe}</code>`;
}

/** One table of constructs. */
function table(list: Snippet[], third: (s: Snippet) => string, head: string): string {
  return `| Construct | Audited example | ${head} |\n|---|---|---|\n${list.map((s) => `| ${s[0]} | ${cell(s)} | ${third(s)} |`).join("\n")}\n`;
}

/** The whole page. */
export function page(): string {
  const same = SNIPPETS.filter((s) => spec[s[0]] === "same");
  const refused = SNIPPETS.filter((s) => spec[s[0]] !== "same");
  return `# Reference: every audited construct

<!-- Generated by tools/gen-spec.ts. Do not edit; run: deno run -A tools/gen-spec.ts -->

[The JavaScript you can write](language.md) explains the subset. This page lists ${SNIPPETS.length} JavaScript
constructs, mostly edge cases, with what machin-js does with each. The tests run every one: it must
behave **the same** under Deno and natively, or be **refused** with the code shown. Changing any
result requires changing this list, so the language can't shift by accident.

It is not a proof that nothing else differs: it covers the constructs listed, with these inputs.
Everyday features are tested separately, and the [known differences](language.md#known-differences)
still apply. An example ending in “…” also uses declarations outside the line shown.

## Behaves the same (${same.length})

These examples run identically. That doesn't make every use of the construct valid: types and the
[readability rules](diagnostics.md) still apply.

${table(same, () => "✓", "Result")}
## Refused (${refused.length})

The code is what you'll see first; some examples report several.

${table(refused, (s) => spec[s[0]].split(" ").map((c) => `\`${c}\``).join(" "), "Code")}`;
}

if (import.meta.main) {
  await Deno.writeTextFile(new URL("../docs/specification.md", import.meta.url), page());
  console.log("wrote docs/specification.md");
}
